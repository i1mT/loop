import assert from "node:assert/strict";
import { test } from "node:test";
import { Db } from "./pg.ts";
import { useDb } from "./db.ts";
import { migrate } from "./migrations.ts";
import { createProject, createTask, getTask, updateProject } from "./tasks.ts";
import { hello } from "./machines.ts";
import { taskDaemonUpdate } from "./daemon-compatibility.ts";
import { claim, reportHead } from "./daemon-api.ts";
import { deliveryAction, deliveryCandidates, getDelivery, previousProductionRecovery, reportDelivery } from "./delivery.ts";
import { acceptTechnicalPlan, approveTechnicalPlan, getTechnicalPlan } from "./task-plan/service.ts";
import { processTaskPlans } from "./task-plan/process.ts";

const url = process.env.DATABASE_URL;

test("交付流程：本地技术方案、预览合入、共享发布与租约恢复", { skip: !url }, async () => {
  const db = new Db(url!);
  await migrate(db);
  useDb(db);
  const id = crypto.randomUUID();
  await hello(db, { machineId: id, name: "测试机器", os: "linux", agents: [{ kind: "grok", installed: true, acp: true, version: null, note: null }] });
  const project = await createProject({ name: "测试仓库", githubRepo: "example/project", machineId: id, agent: "grok" });
  const legacy = await createTask({ projectId: project.id, title: "旧轮次" });
  const env = { url: "https://example.com", username: "tester", password: "demo password", workflow: "deploy.yml" };
  await updateProject(project.id, { deliverySettings: { preview: env, production: env } });
  assert.equal(await getDelivery(db, legacy.id, 1), null);
  await db.prepare("UPDATE tasks SET stage='published' WHERE id=?").bind(legacy.id).run();
  const task = await createTask({ projectId: project.id, title: "预览与生产", planReview: true, releaseReview: false });
  assert.equal(await claim(id, [], true, false), null);
  assert.deepEqual((await taskDaemonUpdate(db, task.id))?.missing, ["delivery"]);
  assert.equal(await taskDaemonUpdate(db, legacy.id), null);
  const work = (await claim(id, [], true, true))!;
  assert.equal(work.task.id, task.id);
  assert.equal(await taskDaemonUpdate(db, task.id), null);
  assert.equal(work.task.mainRef, "dev");
  assert.equal(work.task.job, "work");
  const sha = "a".repeat(40);
  const markdown = ["背景", "目标", "技术实现", "改动点", "验证方式", "风险与回滚"].map((section) => `## ${section}\n记录本阶段的验收与改动细节。`).join("\n");
  await acceptTechnicalPlan(db, { taskId: task.id, round: 1, daemonId: id, leaseId: work.leaseId, title: "交付流程验收", markdown, baselineHead: sha });
  await processTaskPlans(db, { syncWiki: false });
  assert.equal((await getTechnicalPlan(db, task.id))?.phase, "awaiting_review");
  assert.equal(await approveTechnicalPlan(db, task.id, 1), true);
  await db.prepare("UPDATE tasks SET stage='running' WHERE id=?").bind(task.id).run();
  await db.prepare("INSERT INTO sessions(id,task_id,agent,state,created_at,updated_at) VALUES(?,?,'grok','idle',?,?)").bind(id, task.id, Date.now(), Date.now()).run();
  assert.equal((await reportHead(id, work.leaseId, id, sha, { branch: "loop/demo", prNumber: 1 })).ok, true);
  const preview = (await claim(id, [task.id], true, true))!;
  assert.equal(preview.leaseId, work.leaseId);
  assert.equal(preview.task.job, "delivery");
  const fromPreview = { daemonId: id, round: 1, stage: "preview_deploy" } as const;
  assert.equal(await reportDelivery(preview.leaseId, { ...fromPreview, next: "preview_test", state: { previewMerge: sha, previewSha: sha } }), true);
  assert.equal(await reportDelivery(preview.leaseId, { ...fromPreview, next: "preview_test", state: {} }), false);
  const validation = (await claim(id, [], true, true))!;
  const fromValidation = { ...fromPreview, stage: "preview_test" } as const;
  assert.equal(validation.task.sessionId, id);
  assert.equal(await reportDelivery(validation.leaseId, { ...fromValidation, next: "preview_test", state: { previewPassed: false }, error: "智能体没有返回明确的测试通过结果" }), true);
  assert.equal(await claim(id, [], true, true), null);
  const recovered = (await claim(id, [], true, true, [], undefined, true))!;
  assert.equal(recovered.task.sessionId, id);
  const repair = { ...fromValidation, next: "running", state: { previewPassed: false, previewMerge: null }, repair: "修复预览字号后重新提交" } as const;
  assert.equal(await reportDelivery(recovered.leaseId, repair), true);
  assert.equal(await reportDelivery(recovered.leaseId, repair), false);
  const fixing = (await claim(id, [], true, true, [], undefined, true))!;
  assert.equal(fixing.task.sessionId, id);
  assert.equal(fixing.task.round, 1);
  assert.equal(fixing.task.prNumber, null);
  const inbox = await db.prepare("SELECT id,body FROM inbox WHERE task_id=?").bind(task.id).all<{id: number; body: string}>();
  assert.deepEqual(inbox.results.map((message) => message.body), [repair.repair]);
  await db.prepare("UPDATE inbox SET delivered_at=? WHERE id=?").bind(Date.now(), inbox.results[0].id).run();
  assert.equal((await reportHead(id, fixing.leaseId, id, sha, { branch: "loop/demo", prNumber: 4 })).ok, true);
  const redeploy = (await claim(id, [], true, true))!;
  assert.equal(await reportDelivery(redeploy.leaseId, { ...fromPreview, next: "preview_test", state: { previewMerge: sha, previewSha: sha } }), true);
  const retest = (await claim(id, [], true, true))!;
  assert.equal(await reportDelivery(retest.leaseId, { ...fromValidation, next: "production_review", state: { previewPassed: true } }), true);
  const another = await createTask({ projectId: project.id, title: "共享发版" });
  await db.prepare("UPDATE tasks SET stage='preview_test' WHERE id=?").bind(another.id).run();
  await db.prepare("UPDATE task_delivery SET state=jsonb_build_object('previewMerge',?::text),next_at=? WHERE task_id=?")
    .bind(sha, Date.now() + 30000, another.id).run();
  const release = { number: 2, url: "https://example.com/release", head: sha, tasks: [{ id: task.id, round: 1, title: task.title, verification: "passed" as const }, { id: another.id, round: 1, title: another.title, verification: "pending" as const }] };
  const preparing = (await claim(id, [], true, true))!;
  assert.equal((await deliveryCandidates(preparing.leaseId, id))[0]?.sha, sha);
  assert.equal(await reportDelivery(preparing.leaseId, { ...fromPreview, stage: "production_review", next: "production_review", state: { release } }), true);
  assert.equal(await deliveryAction(task.id, "merge", "b".repeat(40), release.number), false);
  assert.equal(await deliveryAction(task.id, "merge", sha, release.number), false);
  assert.equal(await deliveryAction(task.id, "merge", sha, release.number, release.tasks.slice(0, 1)), false);
  const approved = await Promise.all([deliveryAction(task.id, "merge", sha, release.number, release.tasks), deliveryAction(task.id, "merge", sha, release.number, release.tasks)]);
  assert.deepEqual(approved.sort(), [false, true]);
  const production = (await claim(id, [], true, true))!;
  const fromProduction = { daemonId: id, round: 1, stage: "production_deploy" } as const;
  assert.equal(await reportDelivery(production.leaseId, { ...fromProduction, next: "production_test", state: { release, productionMerge: sha } }), true);
  assert.equal((await getDelivery(db, another.id, 1))?.state.productionMerge, sha);
  await db.prepare("UPDATE tasks SET stage='cancelled' WHERE id=?").bind(another.id).run();
  const regression = (await claim(id, [], true, true))!;
  assert.equal(await reportDelivery(regression.leaseId, { ...fromProduction, stage: "production_test", next: "production_test", state: {}, error: "回归失败" }), true);
  assert.equal(await claim(id, [], true, true), null);
  assert.equal((await getTask(task.id))?.merge_sha, sha);
  assert.equal(await deliveryAction(task.id, "retry"), true);
  const retry = (await claim(id, [], true, true))!;
  const repairProduction = {
    ...fromProduction, stage: "production_test", next: "running", repairProduction: true,
    repair: "生产回归失败，请到 dev 修复", state: { productionResult: "发现生产问题", repairCount: 2, repairReasons: ["same-report"] },
  } satisfies Parameters<typeof reportDelivery>[1];
  assert.equal(await reportDelivery(retry.leaseId, repairProduction), true);
  assert.equal(await reportDelivery(retry.leaseId, repairProduction), false);
  const previousProduction = await previousProductionRecovery(db, task.id, 2);
  assert.equal(previousProduction?.sha, sha);
  assert.equal(previousProduction?.result, "发现生产问题");
  assert.deepEqual((await getDelivery(db, task.id, 2))?.state, { repairCount: 2, repairReasons: ["same-report"] });
  assert.equal((await getTask(task.id))?.merge_sha, null);
  const followUp = (await claim(id, [], true, true))!;
  assert.equal(followUp.task.round, 2);
  assert.equal(followUp.task.mainRef, "dev");
  assert.equal(followUp.task.sessionId, id);
  assert.equal(followUp.task.prNumber, null);
  await db.close();
});
